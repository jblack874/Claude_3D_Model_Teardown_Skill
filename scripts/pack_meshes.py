"""Decimate ODRI STLs, center them, put the longest axis on Y, quantize to int16, gzip, write a JS module of base64 strings."""
import sys, json, gzip, base64, numpy as np, trimesh, fast_simplification as fs
src, out = sys.argv[1], sys.argv[2]
PARTS = {  # name: (file, target triangles)
  'upper_base': ('leg_3dof_v1/stl_files/upper_leg_module_shell_base.STL', 4000),
  'upper_cover': ('leg_3dof_v1/stl_files/upper_leg_module_shell_cover.STL', 3000),
  'hipfe_base': ('leg_3dof_v1/stl_files/hip_fe_module_shell_base.STL', 3000),
  'hipfe_cover': ('leg_3dof_v1/stl_files/hip_fe_module_shell_cover.STL', 2500),
  'hipaa_base': ('leg_3dof_v1/stl_files/hip_aa_module_shell_base.STL', 2500),
  'lower_leg': ('leg_3dof_v1/stl_files/lower_leg_v3.STL', 2500),
  'pulley30': ('actuator_module_v1/stl_files/transmission_pulley_at3_t30_output.STL', 1500),
  'body_center': ('quadruped_robot_12dof_v1/stl_files/body_structure_center.STL', 3000),
}
meta, lines = {}, []
for name, (f, tgt) in PARTS.items():
    m = trimesh.load(f"{src}/{f}", force='mesh'); m.merge_vertices()
    r = max(0.0, 1 - tgt / len(m.faces))
    v, fc = fs.simplify(m.vertices.astype(np.float32), m.faces.astype(np.int32), target_reduction=r) if r > 0 else (m.vertices, m.faces)
    v = np.asarray(v, float) / 1000.0  # mm → m
    lo, hi = v.min(0), v.max(0); c = (lo + hi) / 2; ext = hi - lo
    order = np.argsort(-ext)            # longest → Y, middle → X, shortest → Z
    v = (v - c)[:, [order[1], order[0], order[2]]]
    ext = ext[[order[1], order[0], order[2]]]
    s = ext.max() / 2 / 32000
    q = np.round(v / s).astype(np.int16)
    blob = q.tobytes() + np.asarray(fc, np.uint16 if len(v) < 65535 else np.uint32).tobytes()
    meta[name] = {'n': int(len(v)), 'f': int(len(fc)), 's': float(s), 'ext': [round(float(e), 4) for e in ext], 'src': f}
    lines.append(f'  {name}: "{base64.b64encode(gzip.compress(blob, 9)).decode()}",')
    print(name, len(fc), 'tris', [round(float(e)*1000) for e in ext], 'mm')
open(out, 'w').write('// ODRI open hardware STLs (BSD-3), decimated + int16-quantized + gzip. Generated by scripts/pack_meshes.py\nexport const MESH_META = ' + json.dumps(meta) + ';\nexport const MESH = {\n' + '\n'.join(lines) + '\n};\n')
